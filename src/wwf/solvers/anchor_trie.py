"""'Smart brute force': exhaustive move generation after Appel & Jacobson,
"The World's Fastest Scrabble Program" (CACM 1988), using a plain trie.

Across moves are generated row by row from each anchor; down moves are generated by running the
same code on the transposed board and mapping coordinates back.
"""

from __future__ import annotations

import time
from typing import Any

from wwf.core.board import Board, Tile
from wwf.core.config import BoardConfig
from wwf.core.dictionary import Dictionary, TrieNode
from wwf.core.move import Placement, build_move
from wwf.core.rack import BLANK, Rack
from wwf.core.scoring import RawPlacement, score_move, score_raw
from wwf.solvers.base import (
    ScoredMove,
    SolverParam,
    SolverResult,
    leave_after,
    resolve_params,
    sort_key_score_only,
    sort_key_score_then_leave,
)

LetterGrid = list[list[str | None]]


def cross_checks(
    grid: LetterGrid, root: TrieNode, cells: set[tuple[int, int]]
) -> dict[tuple[int, int], frozenset[str]]:
    """For each empty cell in `cells` with a tile directly above or below, the letters that form
    a valid vertical word there. Cells without vertical neighbours are omitted (anything goes)."""
    size = len(grid)
    out: dict[tuple[int, int], frozenset[str]] = {}
    for r, c in cells:
        up_start = r
        while up_start > 0 and grid[up_start - 1][c] is not None:
            up_start -= 1
        down_end = r
        while down_end < size - 1 and grid[down_end + 1][c] is not None:
            down_end += 1
        if up_start == r and down_end == r:
            continue
        node: TrieNode | None = root
        for rr in range(up_start, r):
            assert node is not None
            node = node.children.get(grid[rr][c])  # type: ignore[arg-type]
            if node is None:
                break
        if node is None:
            out[(r, c)] = frozenset()
            continue
        below = [grid[rr][c] for rr in range(r + 1, down_end + 1)]
        allowed: set[str] = set()
        for letter, child in node.children.items():
            n: TrieNode | None = child
            for ch in below:
                n = n.children.get(ch) if n is not None else None  # type: ignore[arg-type]
                if n is None:
                    break
            if n is not None and n.terminal:
                allowed.add(letter)
        out[(r, c)] = frozenset(allowed)
    return out


class _AcrossGenerator:
    """Generates every across move on one (possibly transposed) board.

    The inner loops avoid attribute lookups and allocations where they can: `rack` holds a count
    for every letter and the blank, and found moves are appended as (row, placed-tuple) pairs.
    """

    def __init__(
        self, board: Board, root: TrieNode, rack: dict[str, int], allow_blank: bool
    ) -> None:
        self.size = board.size
        self.grid: LetterGrid = [[t.letter if t else None for t in row] for row in board.cells]
        self.root = root
        self.rack = rack
        self.allow_blank = allow_blank
        self.anchors = board.anchors()
        self.checks = cross_checks(self.grid, root, self.anchors)
        self.checks_by_row: dict[int, dict[int, frozenset[str]]] = {}
        for (r, c), allowed in self.checks.items():
            self.checks_by_row.setdefault(r, {})[c] = allowed
        self.found: list[tuple[int, tuple[tuple[int, str, bool], ...]]] = []
        self.nodes_visited = 0

    def run(self) -> None:
        for r, a in sorted(self.anchors):
            self._from_anchor(r, a)

    def _from_anchor(self, r: int, a: int) -> None:
        row = self.grid[r]
        checks = self.checks_by_row.get(r, {})
        size = self.size
        rack = self.rack
        allow_blank = self.allow_blank
        found = self.found
        placed: list[tuple[int, str, bool]] = []
        visited = 0

        def extend_right(node: TrieNode, col: int) -> None:
            nonlocal visited
            visited += 1
            if col >= size:
                if node.terminal and col > a:
                    found.append((r, tuple(placed)))
                return
            existing = row[col]
            if existing is not None:
                child = node.children.get(existing)
                if child is not None:
                    extend_right(child, col + 1)
                return
            if node.terminal and col > a:
                found.append((r, tuple(placed)))
            allowed = checks.get(col)
            blanks = allow_blank and rack[BLANK] > 0
            for letter, child in node.children.items():
                if allowed is not None and letter not in allowed:
                    continue
                if rack[letter]:
                    rack[letter] -= 1
                    placed.append((col, letter, False))
                    extend_right(child, col + 1)
                    placed.pop()
                    rack[letter] += 1
                if blanks:
                    rack[BLANK] -= 1
                    placed.append((col, letter, True))
                    extend_right(child, col + 1)
                    placed.pop()
                    rack[BLANK] += 1

        if a > 0 and row[a - 1] is not None:
            # Left part is the fixed run of tiles already on the board.
            start = a - 1
            while start > 0 and row[start - 1] is not None:
                start -= 1
            node: TrieNode | None = self.root
            for col in range(start, a):
                assert node is not None
                node = node.children.get(row[col])  # type: ignore[arg-type]
                if node is None:
                    return
            assert node is not None
            extend_right(node, a)
            self.nodes_visited += visited
            return

        # Left part built from the rack, through empty non-anchor cells only. At least one
        # tile must remain for the anchor itself.
        limit = 0
        k = a - 1
        while k >= 0 and row[k] is None and (r, k) not in self.anchors:
            limit += 1
            k -= 1
        limit = min(limit, sum(rack.values()) - 1)
        prefix: list[tuple[str, bool]] = []

        def left_part(node: TrieNode, remaining: int) -> None:
            if prefix:
                first_col = a - len(prefix)
                placed.extend((first_col + i, ch, bl) for i, (ch, bl) in enumerate(prefix))
                extend_right(node, a)
                placed.clear()
            else:
                extend_right(node, a)
            if remaining == 0:
                return
            blanks = allow_blank and rack[BLANK] > 0
            for letter, child in node.children.items():
                if rack[letter]:
                    rack[letter] -= 1
                    prefix.append((letter, False))
                    left_part(child, remaining - 1)
                    prefix.pop()
                    rack[letter] += 1
                if blanks:
                    rack[BLANK] -= 1
                    prefix.append((letter, True))
                    left_part(child, remaining - 1)
                    prefix.pop()
                    rack[BLANK] += 1

        left_part(self.root, limit)
        self.nodes_visited += visited


def generate_raw_moves(
    board: Board, rack: Rack, dictionary: Dictionary, allow_blank: bool = True
) -> tuple[list[tuple[RawPlacement, ...]], dict[str, int]]:
    """Every legal move once, as a tuple of new-tile placements sorted by (row, col)."""
    root = dictionary.root()
    counts = {chr(c): 0 for c in range(ord("A"), ord("Z") + 1)}
    counts[BLANK] = 0
    for t, n in rack.counts().items():
        counts[t] = n
    if not allow_blank:
        counts[BLANK] = 0
    stats = {"anchors": 0, "cross_checks": 0, "candidates": 0, "nodes_visited": 0}
    seen: set[frozenset[RawPlacement]] = set()
    moves: list[tuple[RawPlacement, ...]] = []

    for transposed in (False, True):
        gen = _AcrossGenerator(
            board.transpose() if transposed else board, root, counts, allow_blank
        )
        gen.run()
        stats["anchors"] = len(gen.anchors)
        stats["cross_checks"] += len(gen.checks)
        stats["nodes_visited"] += gen.nodes_visited
        stats["candidates"] += len(gen.found)
        for r, placed in gen.found:
            if transposed:
                raw = tuple((col, r, letter, blank) for col, letter, blank in placed)
            else:
                raw = tuple((r, col, letter, blank) for col, letter, blank in placed)
            # A one-tile move that forms words both ways is found by both passes.
            if len(raw) == 1:
                key = frozenset(raw)
                if key in seen:
                    continue
                seen.add(key)
            moves.append(tuple(sorted(raw)))
    return moves, stats


def _to_scored(
    board: Board, raw: tuple[RawPlacement, ...], rack: Rack, cfg: BoardConfig
) -> ScoredMove:
    move = build_move(board, (Placement(r, c, Tile(letter, blank)) for r, c, letter, blank in raw))
    return ScoredMove(move, score_move(board, move, cfg), leave_after(rack, move))


class AnchorTrieSolver:
    id = "anchor_trie"
    display_name = "Smart brute force"
    description = (
        "Exhaustive legal-move generation (Appel-Jacobson anchors and cross-checks over a trie). "
        "Finds every legal move and ranks by score."
    )
    params: tuple[SolverParam, ...] = (
        SolverParam("max_results", "Max results", "int", 25, min=1, max=500,
                    help="How many top moves to return."),
        SolverParam("min_score", "Minimum score", "int", 0, min=0,
                    help="Drop moves scoring below this."),
        SolverParam("allow_blank_branching", "Use blanks", "bool", True,
                    help="Try every letter for each blank on the rack. Off is faster, "
                         "but ignores blanks entirely."),
        SolverParam("tie_break", "Tie break", "choice", "score_then_leave",
                    choices=("score_then_leave", "score_only"),
                    help="score_then_leave prefers balanced leaves and no Q without U among "
                         "equal scores."),
    )  # fmt: skip

    def solve(
        self, board: Board, rack: Rack, dictionary: Dictionary, cfg: BoardConfig, **params: Any
    ) -> SolverResult:
        p = resolve_params(self.params, params)
        t0 = time.perf_counter()
        raw_moves, stats = generate_raw_moves(board, rack, dictionary, p["allow_blank_branching"])

        # Rank every move by total with the allocation-free scorer, then build full
        # breakdowns only for the moves that can make the cut (all ties at the cutoff included,
        # so the tie-break sees every candidate it needs).
        totals = [(score_raw(board, raw, cfg), raw) for raw in raw_moves]
        totals = [t for t in totals if t[0] >= p["min_score"]]
        totals.sort(key=lambda t: -t[0])
        limit = p["max_results"]
        if len(totals) > limit:
            cutoff = totals[limit - 1][0]
            totals = [t for t in totals if t[0] >= cutoff]
        scored = [_to_scored(board, raw, rack, cfg) for _, raw in totals]

        key = (
            sort_key_score_then_leave
            if p["tie_break"] == "score_then_leave"
            else sort_key_score_only
        )
        scored.sort(key=key)
        stats["moves"] = len(raw_moves)
        elapsed = int((time.perf_counter() - t0) * 1000)
        return SolverResult(tuple(scored[:limit]), elapsed, stats)
